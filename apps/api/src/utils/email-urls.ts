/**
 * Email URL Builders
 * Centralized utilities for generating URLs used in email communications
 *
 * All URLs are built from the dashboard base URL (env.dashboard.baseUrl)
 * This ensures consistency and makes URL updates easier to manage
 */

import { SUPPORT_EMAIL } from '@userplane/shared';

import { env } from '@/api/env';

/**
 * Account Management URLs
 */
export const accountUrls = {
  /**
   * Account deletion confirmation URL
   * Used in account deletion verification emails
   */
  deleteConfirmation: (token: string): string => {
    return `${env.dashboard.baseUrl}/accounts/delete/confirm?token=${token}`;
  },

  /**
   * User feedback URL
   * Used in account deletion confirmation emails
   */
  feedback: (): string => {
    return `${env.dashboard.baseUrl}/feedback`;
  },
} as const;

/**
 * Workspace URLs
 */
export const workspaceUrls = {
  /**
   * Main workspace dashboard URL
   * Used in welcome emails, team notifications, etc.
   */
  dashboard: (workspaceId: string): string => {
    return `${env.dashboard.baseUrl}/workspace/${workspaceId}`;
  },

  /**
   * Workspace restore URL (for canceling scheduled deletions)
   * Used in workspace deletion scheduled emails
   */
  restore: (workspaceId: string): string => {
    return `${env.dashboard.baseUrl}/workspace/restore?type=workspace&id=${workspaceId}`;
  },

  /**
   * Workspace access request URL
   * Used in access request emails to workspace owners
   * Token is generated by TokenService.generateAccessRequestUrl
   */
  accessRequest: (token: string): string => {
    return `${env.dashboard.baseUrl}/workspace/request?token=${token}`;
  },

  /**
   * Workspace creation invite URL (for admin-provisioned workspaces)
   * Used in pilot sandbox invite emails
   * Token is generated by TokenService.generateWorkspaceCreateInviteUrl
   */
  createInvite: (token: string): string => {
    return `${env.dashboard.baseUrl}/workspace/create?token=${token}`;
  },
} as const;

/**
 * Project URLs
 */
export const projectUrls = {
  /**
   * Project restore URL (for canceling scheduled deletions)
   * Used in project deletion scheduled emails
   */
  restore: (workspaceId: string, projectId: string): string => {
    return `${env.dashboard.baseUrl}/workspace/restore?type=project&workspaceId=${workspaceId}&projectId=${projectId}`;
  },
} as const;

/**
 * Recording URLs
 */
export const recordingUrls = {
  /**
   * Recording detail page URL
   * Used in recording received notification emails
   */
  view: (workspaceId: string, recordingId: string): string => {
    return `${env.dashboard.baseUrl}/workspace/${workspaceId}/recordings/${recordingId}`;
  },
} as const;

/**
 * Settings URLs
 */
export const settingsUrls = {
  /**
   * Workspace billing settings URL
   * Used in billing-related emails
   */
  billing: (workspaceId: string): string => {
    return `${env.dashboard.baseUrl}/workspace/${workspaceId}/settings?tab=workspace`;
  },

  /**
   * Domain settings URL
   * Used in domain developer instruction emails
   */
  domains: (workspaceId: string): string => {
    return `${env.dashboard.baseUrl}/workspace/${workspaceId}/settings/domains`;
  },
} as const;

/**
 * Verification URLs
 */
export const verificationUrls = {
  /**
   * Domain verification URL
   * Used for verifying domain ownership via recorder script
   * This URL should be accessible on the user's domain
   */
  domain: (domainUrl: string, token: string): string => {
    return `${domainUrl}?userplane-action=verify&userplane-token=${token}`;
  },

  /**
   * Developer verification URL
   * Used in developer instructions emails to guide developers to domain setup
   * Links to setup page with workspace context and verification token
   */
  developer: (workspaceId: string, domainUrl: string, verificationToken: string): string => {
    return `${env.dashboard.baseUrl}/setup/domain?workspaceId=${workspaceId}&domainURL=${domainUrl}&userplane-token=${verificationToken}`;
  },
} as const;

/**
 * Invite URLs
 * Note: Team invite URLs are generated by TokenService.generateInviteUrl
 * which creates a token and returns the full URL: `/invite?token=${token}`
 */
export const inviteUrls = {
  /**
   * Team invite URL (typically generated by TokenService)
   * Included here for completeness and direct URL construction if needed
   */
  team: (token: string): string => {
    return `${env.dashboard.baseUrl}/invite?token=${token}`;
  },
} as const;

/**
 * Support URLs (external resources)
 */
export const supportUrls = {
  /**
   * Documentation URL
   * Can optionally include a specific path (e.g., '/domains')
   */
  docs: (path?: string): string => {
    const base = env.support.docsUrl;
    return path ? `${base}${path}` : base;
  },

  /**
   * Calendar booking URL (for support calls)
   * Used in pilot welcome emails
   */
  calendar: (): string => {
    return env.support.calendarUrl;
  },

  /**
   * Support email address
   * Used as replyTo in various emails
   */
  email: (): string => {
    return env.support.supportEmail;
  },
} as const;

/**
 * External/Static URLs (company resources)
 */
export const externalUrls = {
  /**
   * Terms of Service URL
   * Used in account suspension and legal-related emails
   */
  terms: (): string => {
    return 'https://userplane.io/terms';
  },

  /**
   * Account appeal/support contact URL
   * Used in account suspension emails
   */
  appeal: (): string => {
    return `mailto:${SUPPORT_EMAIL}?subject=Account%20Appeal`;
  },

  /**
   * Login/authentication URL
   * Used in various account-related emails
   */
  login: (): string => {
    return `${env.dashboard.baseUrl}/auth`;
  },
} as const;

/**
 * All URL builders grouped by category
 * Use this for easy imports: `import { emailUrls } from '@/utils/email-urls'`
 */
export const emailUrls = {
  account: accountUrls,
  workspace: workspaceUrls,
  project: projectUrls,
  recording: recordingUrls,
  settings: settingsUrls,
  verification: verificationUrls,
  invite: inviteUrls,
  support: supportUrls,
  external: externalUrls,
} as const;
